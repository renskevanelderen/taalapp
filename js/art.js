// de taal waarin je op dat moment werkt. Dat laatste kan een emoji niet.
//
// Alles is stroke-gebaseerd met currentColor. Eén regel CSS verandert dus de
// kleur van elke tekening tegelijk. De lijnen zijn bewust niet kaarsrecht en
// de cirkels niet perfect rond — een tekening die te precies is oogt als een
// pictogram, en dat is juist wat we hier niet wilden.

