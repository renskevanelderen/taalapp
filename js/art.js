// Een vlaggetje is geen tekening maar een kleurvlak; twee of drie banen
// volstaan en het leest beter dan een emoji-vlag die op elk toestel anders is.
export function vlag(codeTaal, h = 13) {
  const w = Math.round(h * 1.45);
  const banen =
    codeTaal === "fr"
      ? ["#2b3a8f", "#f7f7f7", "#e0384a"]
      : ["#d8232a", "#f2b705", "#d8232a"];
  const delen =
    codeTaal === "fr"
      ? banen.map((c, i) => `<rect x="${(i * w) / 3}" y="0" width="${w / 3}" height="${h}" fill="${c}"/>`)
      : [
          `<rect x="0" y="0" width="${w}" height="${h * 0.25}" fill="${banen[0]}"/>`,
          `<rect x="0" y="${h * 0.25}" width="${w}" height="${h * 0.5}" fill="${banen[1]}"/>`,
          `<rect x="0" y="${h * 0.75}" width="${w}" height="${h * 0.25}" fill="${banen[2]}"/>`,
        ];
  return `<svg class="vlag" width="${w}" height="${h}" viewBox="0 0 ${w} ${h}" aria-hidden="true" focusable="false"><g>${delen.join("")}</g><rect x="0.4" y="0.4" width="${w - 0.8}" height="${h - 0.8}" fill="none" stroke="rgba(0,0,0,.18)" stroke-width="0.8" rx="1.5"/></svg>`;
}

